@dataclass(frozen=True)
class AdapterToolInfo:
    legacy_name: str
    description: str
    input_schema: dict[str, Any]
    output_schema: dict[str, Any]
    side_effect: bool



def _keywords(*values: str) -> list[str]:
    out: list[str] = []
    for value in values:
        raw = str(value or "").strip()
        if not raw:
            continue
        for part in [raw, raw.lower(), raw.replace("表", ""), raw.replace("清单", "")]:
            part = part.strip()
            if part and part not in out:
                out.append(part)
    return out


def _matches(text: str, keywords: list[str]) -> bool:
    low = str(text or "").lower()
    return any(k.lower() in low for k in keywords if k)


def _match_score(text: str, keywords: list[str]) -> int:
    low = str(text or "").lower()
    score = 0
    for idx, key in enumerate(keywords):
        k = key.lower()
        if not k:
            continue
        if low == k:
            score += 100 - idx
        elif k in low:
            score += 30 - min(idx, 20)
    return score


def _select_table(tables: list[dict[str, Any]], keywords: list[str]) -> dict[str, Any] | None:
    if not tables:
        return None
    scored = []
    for table in tables:
        score = _match_score(str(table.get("name") or ""), keywords)
        scored.append((score, table))
    scored.sort(key=lambda item: item[0], reverse=True)
    if scored and scored[0][0] > 0:
        return scored[0][1]
    return tables[0]


class FeishuToolAdapter:
    """Bridge all tools from the user's ``feishu_adapter`` package into the current ToolExecutor.

    The wrapped adapter remains application-token based by default. To keep the runtime app-tool-only,
    any ``user_access_token`` field generated by an LLM is stripped before invoking legacy tools.
    """

    def __init__(self, *, config: FeishuConfig | None = None, client: Any | None = None) -> None:
        self.config = config or load_feishu_config()
        self.client = client
        self._legacy_registry = None
        self._legacy_runtime = None
        self._legacy_event_bus = None
        self._tool_infos: dict[str, AdapterToolInfo] = {}
        self._inbound_handler: Callable[[dict[str, Any]], Any] | None = None
        self._pump_started = False
        self._pump_lock = threading.Lock()
        # The original adapter starts Feishu IM WebSocket from register() when this env is on.
        # Default it on so the adapter is actually wired when credentials and lark-oapi exist.
        os.environ.setdefault("FEISHU_ENABLE_IM_WS", "1")
        try:
            self.bitable_schema: BitableSchema | None = load_bitable_schema(app_token=self.config.bitable_app_token)
        except BitableSchemaError:
            self.bitable_schema = None
        self._load_legacy_adapter()

    @property
    def ready(self) -> bool:
        return bool(self.config.app_id and self.config.app_secret)

    @property
    def tool_infos(self) -> dict[str, AdapterToolInfo]:
        return dict(self._tool_infos)

    def bind_inbound_handler(self, handler: Callable[[dict[str, Any]], Any]) -> None:
        """Route legacy Feishu WS message events into the current runtime."""
        self._inbound_handler = handler
        self._ensure_event_pump()

    def register(self, registry: ToolRegistry) -> None:
        for name, info in sorted(self._tool_infos.items()):
            registry.register(
                ToolSpec(
                    name=name,
                    description=info.description,
                    args_schema=info.input_schema,
                    side_effect=info.side_effect,
                    handler=self._make_handler(name),
                    auth_type="app",
                )
            )
        self._register_common_aliases(registry)

    def _load_legacy_adapter(self) -> None:
        from tool_integration.events import EventBus
        from tool_integration.runtime import ToolRuntime
        from tool_integration.tools import ToolRegistry as LegacyToolRegistry

        import feishu_adapter.feishu_bitable as feishu_bitable
        import feishu_adapter.feishu_contact as feishu_contact
        import feishu_adapter.feishu_docx as feishu_docx
        import feishu_adapter.feishu_drive as feishu_drive
        import feishu_adapter.feishu_im_group as feishu_im_group
        import feishu_adapter.feishu_im_message as feishu_im_message
        import feishu_adapter.feishu_message_tools as feishu_message_tools
        import feishu_adapter.feishu_wiki as feishu_wiki

        self._legacy_event_bus = EventBus()
        self._legacy_event_bus.subscribe("current_runtime_bridge", ["*"])
        legacy_registry = LegacyToolRegistry()
        modules = [
            feishu_message_tools,
            feishu_contact,
            feishu_im_group,
            feishu_im_message,
            feishu_bitable,
            feishu_docx,
            feishu_drive,
            feishu_wiki,
        ]
        for module in modules:
            self._call_register(module, legacy_registry, self._legacy_event_bus)
        self._legacy_registry = legacy_registry
        self._legacy_runtime = ToolRuntime(legacy_registry, self._legacy_event_bus, config=dict(os.environ))
        self._tool_infos = {
            name: AdapterToolInfo(
                legacy_name=name,
                description=tool.spec.description,
                input_schema=self._app_only_schema(tool.spec.input_schema),
                output_schema=tool.spec.output_schema,
                side_effect=self._infer_side_effect(name),
            )
            for name, tool in legacy_registry.tools.items()
        }

    @staticmethod
    def _call_register(module: Any, registry: Any, event_bus: Any) -> None:
        fn = getattr(module, "register", None)
        if not callable(fn):
            return
        try:
            sig = inspect.signature(fn)
            if "event_bus" in sig.parameters:
                fn(registry, event_bus=event_bus)
            else:
                fn(registry)
        except TypeError:
            fn(registry)

    def _make_handler(self, legacy_name: str) -> Callable[[dict[str, Any]], dict[str, Any]]:
        def handler(args: dict[str, Any]) -> dict[str, Any]:
            if self._legacy_runtime is None:
                raise RuntimeError("legacy feishu_adapter runtime is not loaded")
            clean_args = self._app_only_args(args)
            result = self._legacy_runtime.invoke(legacy_name, clean_args)
            self._drain_legacy_events_once()
            if not result.get("ok"):
                raise RuntimeError(result.get("message") or result.get("error_type") or str(result))
            if "result" in result:
                return result["result"] if isinstance(result["result"], dict) else {"result": result["result"]}
            return result
        return handler

