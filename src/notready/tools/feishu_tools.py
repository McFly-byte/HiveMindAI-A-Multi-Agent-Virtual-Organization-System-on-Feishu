    def _create_named_record(self, args: dict[str, Any]) -> dict[str, Any]:
        if self.bitable_schema is None:
            raise RuntimeError("未加载多维表格 schema：请提供 config/bitable_schema.yaml 和 FEISHU_BITABLE_APP_TOKEN")
        table = self.bitable_schema.get_table(str(args.get("table_key") or ""))
        fields = clean_record_fields(table, args.get("fields") if isinstance(args.get("fields"), dict) else {}, strict=bool(args.get("strict", True)))
        return self._legacy_call_result("feishu_bitable_create_record", {
            "app_token": self.bitable_schema.app_token,
            "table_id": table.table_id,
            "fields": fields,
        })

    def _batch_create_named_records(self, args: dict[str, Any]) -> dict[str, Any]:
        if self.bitable_schema is None:
            raise RuntimeError("未加载多维表格 schema：请提供 config/bitable_schema.yaml 和 FEISHU_BITABLE_APP_TOKEN")
        table = self.bitable_schema.get_table(str(args.get("table_key") or ""))
        strict = bool(args.get("strict", True))
        raw_records = args.get("records") if isinstance(args.get("records"), list) else []
        if not raw_records:
            raise RuntimeError("records 不能为空")
        records: list[dict[str, Any]] = []
        for item in raw_records:
            if not isinstance(item, dict):
                raise RuntimeError("records 每项必须是 object")
            raw_fields = item.get("fields") if isinstance(item.get("fields"), dict) else item
            fields = clean_record_fields(table, raw_fields, strict=strict)
            records.append({"fields": fields})
        return self._legacy_call_result("feishu_bitable_batch_create_records", {
            "app_token": self.bitable_schema.app_token,
            "table_id": table.table_id,
            "records": records,
        })

    def _make_alias_handler(self, legacy_name: str, transform: Callable[[dict[str, Any]], dict[str, Any]]) -> Callable[[dict[str, Any]], dict[str, Any]]:
        legacy_handler = self._make_handler(legacy_name)
        def handler(args: dict[str, Any]) -> dict[str, Any]:
            return legacy_handler(transform(args))
        return handler

    def _legacy_call_result(self, legacy_name: str, args: dict[str, Any]) -> dict[str, Any]:
        if self._legacy_runtime is None:
            raise RuntimeError("legacy feishu_adapter runtime is not loaded")
        result = self._legacy_runtime.invoke(legacy_name, self._app_only_args(args))
        self._drain_legacy_events_once()
        if not result.get("ok"):
            raise RuntimeError(result.get("message") or result.get("error_type") or str(result))
        payload = result.get("result")
        return payload if isinstance(payload, dict) else {"result": payload}

    def _find_bitable_table(self, args: dict[str, Any]) -> dict[str, Any]:
        query = str(args.get("query") or "风险").strip()
        table_query = str(args.get("table_query") or query or "风险表").strip()
        space_query = str(args.get("space_query") or "").strip()
        max_spaces = max(1, min(int(args.get("max_spaces") or 20), 50))
        max_depth = max(0, min(int(args.get("max_depth") or 2), 4))
        page_size = max(1, min(int(args.get("page_size") or 50), 100))
        keywords = _keywords(query, table_query, "风险", "风险表", "风险清单", "risk")
        table_keywords = _keywords(table_query, query, "风险", "风险表", "风险清单", "risk")

        candidates: list[dict[str, Any]] = []
        spaces_page = self._legacy_call_result("feishu_wiki_list_spaces", {"page_size": max_spaces})
        spaces = spaces_page.get("items") if isinstance(spaces_page.get("items"), list) else []
        for space in spaces:
            if not isinstance(space, dict):
                continue
            space_id = str(space.get("space_id") or "")
            space_name = str(space.get("name") or "")
            if not space_id:
                continue
            if space_query and not _matches(space_name, [space_query]):
                continue
            queue: list[tuple[str, int]] = [("", 0)]
            while queue:
                parent, depth = queue.pop(0)
                nodes_page = self._legacy_call_result(
                    "feishu_wiki_list_nodes",
                    {"space_id": space_id, "parent_node_token": parent, "page_size": page_size},
                )
                nodes = nodes_page.get("items") if isinstance(nodes_page.get("items"), list) else []
                for node in nodes:
                    if not isinstance(node, dict):
                        continue
                    title = str(node.get("title") or "")
                    obj_type = str(node.get("obj_type") or "")
                    obj_token = str(node.get("obj_token") or "")
                    node_token = str(node.get("node_token") or "")
                    if obj_type == "bitable" and obj_token:
                        score = _match_score(title, keywords)
                        candidates.append({
                            "score": score,
                            "app_token": obj_token,
                            "app_title": title,
                            "space_id": space_id,
                            "space_name": space_name,
                            "node_token": node_token,
                        })
                    if depth < max_depth and node.get("has_child") and node_token:
                        queue.append((node_token, depth + 1))

        candidates.sort(key=lambda item: int(item.get("score") or 0), reverse=True)
        tried: list[dict[str, Any]] = []
        for candidate in candidates:
            app_token = str(candidate.get("app_token") or "")
            if not app_token:
                continue
            tables_page = self._legacy_call_result("feishu_bitable_list_tables", {"app_token": app_token, "page_size": page_size})
            tables = tables_page.get("items") if isinstance(tables_page.get("items"), list) else []
            normalized_tables = [table for table in tables if isinstance(table, dict)]
            table = _select_table(normalized_tables, table_keywords)
            tried.append({"app_token": app_token, "app_title": candidate.get("app_title"), "tables": normalized_tables[:10]})
            if table:
                return {
                    "app_token": app_token,
                    "table_id": str(table.get("table_id") or ""),
                    "table_name": str(table.get("name") or ""),
                    "app_title": str(candidate.get("app_title") or ""),
                    "space_id": str(candidate.get("space_id") or ""),
                    "space_name": str(candidate.get("space_name") or ""),
                    "node_token": str(candidate.get("node_token") or ""),
                    "matched_by": "wiki_bitable_node_and_table_name",
                    "candidates": candidates[:10],
                }
        raise RuntimeError(f"没有找到匹配的风险多维表格：query={query}, table_query={table_query}, tried={tried[:5]}")

    @staticmethod
    def _alias_create_chat_args(args: dict[str, Any]) -> dict[str, Any]:
        users = args.get("user_id_list") if isinstance(args.get("user_id_list"), list) else []
        one = args.get("user_id") or args.get("open_id")
        if one and not users:
            users = [one]
        return {
            "user_id_list": users,
            "name": args.get("name") or "应用私聊",
            "description": args.get("description") or "由应用工具创建",
            "user_id_type": args.get("user_id_type") or ("open_id" if args.get("open_id") and not args.get("user_id") else "user_id"),
        }

    @staticmethod
    def _app_only_schema(schema: dict[str, Any]) -> dict[str, Any]:
        if not isinstance(schema, dict):
            return {"type": "object", "properties": {}}
        clean = dict(schema)
        props = dict(clean.get("properties") or {})
        props.pop("user_access_token", None)
        clean["properties"] = props
        required = clean.get("required")
        if isinstance(required, list):
            clean["required"] = [x for x in required if x != "user_access_token"]
        return clean

    @staticmethod
    def _app_only_args(args: dict[str, Any]) -> dict[str, Any]:
        clean = dict(args or {})
        clean.pop("user_access_token", None)
        return clean

    @staticmethod
    def _infer_side_effect(name: str) -> bool:
        raw = name.lower().replace("-", "_").replace(".", "_")
        tail = raw
        for prefix in ("feishu_",):
            if tail.startswith(prefix):
                tail = tail[len(prefix):]
        if any(word in tail for word in WRITE_WORDS):
            return True
        if any(tail.startswith(prefix) or f"_{prefix}" in tail for prefix in READ_PREFIXES):
            return False
        return True

    def _ensure_event_pump(self) -> None:
        if self._legacy_event_bus is None:
            return
        with self._pump_lock:
            if self._pump_started:
                return
            self._pump_started = True
        threading.Thread(target=self._event_pump_loop, daemon=True, name="feishu-adapter-event-pump").start()

    def _event_pump_loop(self) -> None:
        while True:
            try:
                self._drain_legacy_events_once()
            except Exception:
                pass
            time.sleep(0.2)

    def _drain_legacy_events_once(self) -> None:
        if self._legacy_event_bus is None:
            return
        events = self._legacy_event_bus.drain("current_runtime_bridge")
        for ev in events:
            event_type = str(getattr(ev, "event_type", ""))
            payload = getattr(ev, "payload", {}) or {}
            if event_type == "feishu.im.message.received" and self._inbound_handler:
                raw = payload.get("raw") if isinstance(payload, dict) else None
                if isinstance(raw, dict):
                    self._inbound_handler(raw)
